    <div class="ayuda-header" id="introduccion">Introducción</div>
    <div class="ayuda-texto">
        <p>
            ¡Bienvenido al manual de usuario del <i>Sistema de Gestión de Tareas e Inventario
            para la Dirección de Servicios Generales del UPTAEB!</i>
        </p>
        <p>
            Sabemos lo importante que es su trabajo diario para el funcionamiento óptimo
            de nuestra universidad. Este sistema ha sido diseñado pensando precisamente en
            usted y en facilitar su labor. Olvídese de los procesos manuales y
            repetitivos; con esta herramienta, podrá gestionar y asignar tareas de forma
            más eficiente y llevar un control preciso del inventario de su departamento,
            liberando tiempo valioso para que pueda enfocarse en lo que realmente importa.
        </p>
        <p>
            Este manual es su guía paso a paso para dominar el sistema. Lo hemos creado
            con un lenguaje claro y sencillo, asumiendo que tiene una experiencia media
            con computadoras, para que pueda aprender a utilizarlo sin complicaciones.
            Queremos que se sienta cómodo y seguro al explotar todas las funcionalidades
            que le permitirán "automatizar" y optimizar sus operaciones diarias.
        </p>
        <div class="ayuda-sub-header" id="objetivos-clave">Objetivos Clave del Manual</div>
        <p>
            Este manual ha sido desarrollado con los siguientes objetivos principales:
        </p>
        <ul>
            <li>
                Capacitar al usuario en la gestión eficiente de tareas: Proporcionar las
                instrucciones claras y concisas necesarias para que los trabajadores de
                Servicios Generales puedan crear, asignar, modificar y dar seguimiento a
                las tareas diarias de manera efectiva dentro del sistema, asegurando que
                ninguna actividad quede sin atención y se optimice el flujo de trabajo.
            </li>
            <li>
                Facilitar el control y la administración del inventario: Guiar al usuario
                paso a paso en el registro, actualización y consulta de los ítems del
                inventario, permitiendo una gestión precisa de los recursos disponibles y
                minimizando las pérdidas o la falta de materiales esenciales para las
                operaciones.
            </li>
            <li>
                Promover la autonomía y confianza del usuario: Ofrecer una guía didáctica
                y accesible que permita a los usuarios con experiencia media en
                computación operar el sistema de forma independiente y segura, resolviendo
                dudas comunes y fomentando la adopción plena de la herramienta para
                maximizar los beneficios de la "automatización" en sus actividades
                cotidianas.
            </li>
        </ul>
    </div>
</section>