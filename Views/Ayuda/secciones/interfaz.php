    <div class="ayuda-texto">
        <p>
            La interfaz de usuario del sistema está diseñada para ser intuitiva y fácil de usar.
            A continuación, se describen los elementos principales que encontrará en la pantalla
            principal del sistema.
        </p>
        <ul>
            <li>
                <b>Cabecera:</b>
                <ul>
                    <li>
                        Ubicada en la parte superior de la interfaz. A su izquierda contiene el
                        nombre del sistema, junto con un botón para abrir o cerrar el menú
                        lateral del sistema. En la parte derecha muestra un botón para ver
                        las notificaciones del usuario.
                    </li>
                </ul>
                <div class="img">
                    <img src="public/img/ayuda/img02.png" alt="Cabecera de la interfaz">
                    <div>Cabecera de la interfaz</div>
                </div>
            </li>
            <li>
                <b>Menú lateral:</b>
                <ul>
                    <li>
                        En la parte superior se muestra el nombre del usuario que ha
                        iniciado sesión, el rol que tiene asignado y un botón para cerrar
                        sesión.
                    </li>
                    <li>
                        En su parte inferior contiene accesos directos a los modulos del
                        sistema, como, "Tareas", "Trabajadores", "Inventario", etc.
                    </li>
                    <li>
                        Puede expandirse o contraerse según sus preferencias con el botón
                        en la cabecera mencionado anteriormente.
                    </li>
                </ul>
                <div class="img">
                    <img src="public/img/ayuda/img03.png" alt="Menú lateral de la interfaz" width="200">
                    <div>Menú lateral de la interfaz</div>
                </div>
            </li>
            <li>
                <b>Área de contenido principal:</b>
                <ul>
                    <li>Aquí se mostrarán las tablas y formularios según la sección seleccionada.</li>
                    <li>Incluye botones para agregar, modificar o eliminar registros según los permisos del usuario.</li>
                </ul>
            </li>
    </div>
